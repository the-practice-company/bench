"""Список файлов, записанных агентом в текущем ходе.

`Stop` отличает по нему «сломал агент сейчас» от «сломал человек в Obsidian».
Без этого различия человек, оборвавший ссылку в Obsidian, заблокировал бы
работу агента.

Живёт в `.git/`: файл обязан пережить несколько вызовов инструментов, не может
лежать вне корня (незыблемое №6) и не имеет права делать дерево грязным —
`.git/` единственное место внутри корня, которое git по построению не
показывает в `git status`. Разводка «незакоммиченное = здесь работал человек»
несущая: на ней стоят и `SessionStart`, и `Stop`, и хук, пачкающий дерево на
каждой записи, ломает её насовсем.

Остаточный риск назван: `.git/` чистится сборщиком мусора git не всегда
предсказуемо. Потеря файла деградирует `Stop` до «считать все незакоммиченные
файлы чужими», то есть до сообщения вместо блока. Это ослабление, а не
поломка, и оно проверяется тестом.
"""

import re
from pathlib import Path

# `session_id` приходит снаружи и попадает в имя файла целиком. Всё, кроме
# буквы, цифры и трёх безопасных знаков, гасится: разделитель пути увёл бы
# запись из `.git/` — то есть за границу, которую держит незыблемое №6.
_SAFE = re.compile(r"[^A-Za-z0-9_.-]")


def _git_dir(root):
    """Настоящий каталог `.git` этого корня, или None.

    У сабмодуля и у рабочего дерева git `.git` — не каталог, а файл со
    строкой `gitdir: путь`. Проверка «родитель цели существует» на таком
    файле истинна, и запись падала `NotADirectoryError`: умирал весь
    `PostToolUse`, а вместе с ним пропадал отчёт гейтов по только что
    записанному файлу. Причиной в stderr значился код возврата hook.py.

    Указатель бывает и относительным (так пишет сабмодуль), и абсолютным
    (так пишет `git worktree`); относительный считается от корня. Указатель,
    который никуда не ведёт, — не обвал, а описанное ниже ослабление.
    """
    marker = Path(root) / ".git"
    if marker.is_dir():
        return marker
    if not marker.is_file():
        return None
    try:
        text = marker.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None
    for line in text.splitlines():
        if not line.startswith("gitdir:"):
            continue
        pointed = Path(line.split(":", 1)[1].strip())
        if not pointed.is_absolute():
            pointed = Path(root) / pointed
        return pointed if pointed.is_dir() else None
    return None


def _path(git_dir, session_id):
    return Path(git_dir) / ("twinkle-turn-%s" % _SAFE.sub("_", str(session_id)))


def record(root, session_id, rel_path):
    """Дописать путь в список хода. Возвращает, удалось ли.

    Ответ возвращается, а не проглатывается: `.git` может оказаться
    указателем в никуда, и тогда писать список некуда. Промолчать в этом
    месте — завести молчаливую заглушку (незыблемое №4): `Stop` счёл бы
    чужим всё, что агент только что написал, и не сказал бы, почему. Строку
    об этом печатает обработчик — печатать из библиотеки нельзя, её зовут и
    там, где stderr занят отчётом.

    Отказ файловой системы уходит в тот же ответ, а не наружу исключением:
    отчёт по записанному файлу не имеет права исчезать из-за того, что не
    удалось завести служебный файл.
    """
    git_dir = _git_dir(root)
    if git_dir is None:
        return False
    try:
        with _path(git_dir, session_id).open("a", encoding="utf-8") as handle:
            handle.write(rel_path + "\n")
    except OSError:
        return False
    return True


def readable(root):
    """Есть ли вообще где вести список хода.

    Пустой список отвечает сразу на два разных вопроса — «в этом ходе ничего
    не писали» и «писать было некуда», — а `Stop` из первого делает «блокировать
    нечего», из второго «блокировать не могу». Второе обязано быть сказано
    вслух: молчаливое ослабление блокирующего правила — это заглушка
    (незыблемое №4).

    Наблюдаемая конфигурация, в которой ответ «нет», — контекстный репозиторий
    подкаталогом кодового: маркер рецепта в `context/`, а `.git` выше, и своего
    `.git` у корня рецепта нет вовсе.
    """
    return _git_dir(root) is not None


def listing(root, session_id):
    """Пути хода в порядке первого появления, без повторов.

    Повтор — обычное дело, а не исключение: ход из `Write` и двух `Edit` по
    одному файлу пишет одну и ту же строку трижды. Список отвечает на вопрос
    «какие файлы тронуты», и повтор в нём умножил бы на число правок и
    `git add` чекпоинта, и сообщения `Stop`.

    Файла нет — пустой список, а не ошибка: это и есть названное выше
    ослабление, и вести оно обязано к сообщению, а не к обвалу. Каталога
    `.git` тоже может не быть — тот же ответ по той же причине.
    """
    git_dir = _git_dir(root)
    if git_dir is None:
        return []
    target = _path(git_dir, session_id)
    if not target.exists():
        return []
    out = []
    for line in target.read_text(encoding="utf-8").split("\n"):
        if line and line not in out:
            out.append(line)
    return out
