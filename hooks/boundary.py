"""Граница рабочего каталога: всё, что плагин меняет, лежит внутри корня.

Незыблемое №6 целиком держится на этом модуле. Нормализация идёт **до**
сравнения: `..`, симлинк и абсолютный путь обязаны давать один и тот же
ответ. Сравнение по префиксу строки без нормализации ловится собственным
`..` и потому не годится — та же ошибка, которую `escapes_root` волны 1
уже один раз пережил.

Ограничение — на изменение, не на чтение: код плагина живёт вне репозитория
и зовётся через `${CLAUDE_PLUGIN_ROOT}`, запрет на чтение отключил бы плагин
целиком.
"""

import os
from pathlib import Path

MARKER = ".twinkle-repo-builder"


def find_root(start):
    """Вверх до ближайшего маркера; корнем он становится, если лежит в git.

    Корень — место маркера, а не поле в конфиге: поля с путём зон не
    существует и не может появиться, потому что искать корень по конфигу,
    который лежит в корне, — круг (секция 22).

    Второе условие взято из уже принятого: git обязателен (секция 8), значит
    маркер вне всякого репозитория корнем не является — там не будет ни
    истории, ни чекпоинтов, ни списка файлов хода.

    Записано это как «git есть где-то на пути вверх от маркера», и обе
    половины формулировки оплачены:

    - **не «поиск останавливается на первом `.git`»**. `knowledge/` держит
      чужие сабмодули по построению (`zones.READ_ONLY` заведён ровно для
      них), и остановка на первом `.git` означала, что ход с `cwd` внутри
      сабмодуля не находил корня вовсе. Незыблемое №6 переставало
      проверяться для **любой** цели, а не только для целей внутри
      `knowledge`;
    - **не «`.git` рядом с маркером»**. Контекстный репозиторий законно
      живёт подкаталогом кодового, и тогда `.git` лежит выше маркера. Это
      не гипотеза: на разъехавшиеся корни у `SessionStart` заведена своя
      ветка — пути `--porcelain` считаются от корня git, пути гейтов от
      корня рецепта, и чекпоинт в такой конфигурации не делается.

    Ближайший маркер и решает: не нашлось git над ним — `None`, а не поиск
    следующего маркера выше. Второй маркер над сломанным репозиторием — это
    чужой репозиторий, и уводить работу в него молча нельзя.

    `.git` бывает и файлом-указателем — так выглядят сабмодуль и рабочее
    дерево git, — поэтому здесь `exists`, а не `is_dir`: требовать каталога
    значило бы не найти корня там, где он есть.

    Возвращает нормализованный путь — он же база для `outside`; вернуть
    ненормализованный значило бы сравнивать с ним нормализованную цель.
    Маркера нет — `None`: репозиторий не проходил ни CREATE, ни ADOPT, и
    подставлять вместо корня рабочую папку нельзя (незыблемое №4).
    """
    chain = [Path(start).resolve()]
    chain.extend(chain[0].parents)
    for index, candidate in enumerate(chain):
        if not (candidate / MARKER).exists():
            continue
        if any((above / ".git").exists() for above in chain[index:]):
            return candidate
        return None
    return None


def outside(path, root):
    """Лежит ли путь за корнем после полной нормализации.

    `os.path.realpath` разворачивает симлинки и схлопывает `..` — без него
    `repo/areas/../../x` считался бы лежащим внутри `repo`, а симлинк наружу
    был бы дырой в границе размером с файловую систему.

    Сравнение идёт по кортежу сегментов, а не по префиксу строки: соседний
    каталог `repo-neighbour` начинается на `repo` и при строковом сравнении
    прошёл бы за свой.
    """
    resolved = Path(os.path.realpath(str(path)))
    base = Path(os.path.realpath(str(root)))
    return resolved.parts[:len(base.parts)] != base.parts
