#!/bin/sh
# Единственная работа шима — не дать «не смог» выглядеть как «разрешил».
# Если python отсутствует или падает при импорте, здесь печатается видимая
# строка с причиной и возвращается 0: код 2 означает нарушение, и только его.
# Урок оплачен чужой болью: у изученного аналога хук возвращал 1 на каждом
# вызове из-за отсутствия flock на macOS, это читалось как «занято», и
# автокоммиты молча отключились у всех пользователей macOS.
#
# Переменная нужна тесту, чтобы подсунуть заведомо отсутствующий интерпретатор.
PY="${TWINKLE_PYTHON:-python3}"
DIR=$(dirname "$0")

# Наличие интерпретатора выясняется подстановкой команды, а не отправкой обеих
# струй вывода в пустоту. Такое перенаправление — один из трёх шаблонов,
# дословно запрещённых тестом (tests/test_hook_entry.py::TestNoSilencing):
# ровно ими отказ и превращают в тишину. Проверка читает файл целиком и
# буквально, поэтому запрещённое здесь не называется даже в комментарии —
# та же причина, по которой `_ABSOLUTE_PREFIXES` в scripts/check_package.py
# собран из кусков: иначе файл находит сам себя.
# Подстановка забирает stdout `command -v` и ничего не гасит: единственная
# диагностика — та, что печатается ниже своими руками.
RESOLVED=$(command -v "$PY")
if [ -z "$RESOLVED" ] && [ ! -x "$PY" ]; then
    echo "гейт не выполнился: интерпретатор $PY не найден" >&2
    exit 0
fi

# Коды рукопожатия. Их единственная работа — доказать, что отработал именно
# hook.py: любой другой код, включая 0 и 2, означает «не смог». Пропускать 2
# наружу без такого доказательства нельзя — своя двойка бывает у обёрток venv
# и pyenv, и в Claude Code она приезжает блокировкой записи без причины. Ноль
# без доказательства не лучше: его вернёт любая посторонняя команда на месте
# python — скажем, echo, — и гейт молча разрешит всё.
# Числа обязаны совпадать с EXIT_CHECKED_* в hook.py; за этим следит
# tests/test_hook_entry.py::TestHandshake.
CHECKED_OK=91
CHECKED_VIOLATION=92

"$PY" "$DIR/hook.py" "$@"
CODE=$?
if [ $CODE -eq $CHECKED_OK ]; then
    exit 0
fi
if [ $CODE -eq $CHECKED_VIOLATION ]; then
    exit 2
fi
# Падение интерпретатора, сбой импорта, сигнал, чужой код возврата. Ядро
# прочитает любой ненулевой код как неблокирующую ошибку и промолчит, поэтому
# причина называется здесь.
echo "гейт не выполнился: hook.py не подтвердил проверку, код возврата $CODE" >&2
exit 0
