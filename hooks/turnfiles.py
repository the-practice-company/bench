"""Список файлов, записанных агентом в текущем ходе.

`Stop` отличает по нему «сломал агент сейчас» от «сломал человек в Obsidian».
Без этого различия человек, оборвавший ссылку в Obsidian, заблокировал бы
работу агента.

Живёт в `.git/`: файл обязан пережить несколько вызовов инструментов, не может
лежать вне корня (незыблемое №6) и не имеет права делать дерево грязным —
`.git/` единственное место внутри корня, которое git по построению не
показывает в `git status`. Разводка «незакоммиченное = здесь работал человек»
несущая: на ней стоят и `SessionStart`, и `Stop`, и хук, пачкающий дерево на
каждой записи, ломает её насовсем.

Остаточный риск назван: `.git/` чистится сборщиком мусора git не всегда
предсказуемо. Потеря файла деградирует `Stop` до «считать все незакоммиченные
файлы чужими», то есть до сообщения вместо блока. Это ослабление, а не
поломка, и оно проверяется тестом.
"""

import re
from pathlib import Path

# `session_id` приходит снаружи и попадает в имя файла целиком. Всё, кроме
# буквы, цифры и трёх безопасных знаков, гасится: разделитель пути увёл бы
# запись из `.git/` — то есть за границу, которую держит незыблемое №6.
_SAFE = re.compile(r"[^A-Za-z0-9_.-]")


def _path(root, session_id):
    return Path(root) / ".git" / ("twinkle-turn-%s" % _SAFE.sub("_", str(session_id)))


def record(root, session_id, rel_path):
    """Дописать путь в список хода. Возвращает, удалось ли.

    Ответ возвращается, а не проглатывается: маркер рецепта ищется раньше
    `.git`, поэтому корень может найтись там, где писать список некуда.
    Промолчать в этом месте — завести молчаливую заглушку (незыблемое №4):
    `Stop` счёл бы чужим всё, что агент только что написал, и не сказал бы,
    почему. Строку об этом печатает обработчик — печатать из библиотеки
    нельзя, её зовут и там, где stderr занят отчётом.
    """
    target = _path(root, session_id)
    if not target.parent.exists():
        return False
    with target.open("a", encoding="utf-8") as handle:
        handle.write(rel_path + "\n")
    return True


def listing(root, session_id):
    """Пути хода в порядке первого появления, без повторов.

    Повтор — обычное дело, а не исключение: ход из `Write` и двух `Edit` по
    одному файлу пишет одну и ту же строку трижды. Список отвечает на вопрос
    «какие файлы тронуты», и повтор в нём умножил бы на число правок и
    `git add` чекпоинта, и сообщения `Stop`.

    Файла нет — пустой список, а не ошибка: это и есть названное выше
    ослабление, и вести оно обязано к сообщению, а не к обвалу.
    """
    target = _path(root, session_id)
    if not target.exists():
        return []
    out = []
    for line in target.read_text(encoding="utf-8").split("\n"):
        if line and line not in out:
            out.append(line)
    return out
